  get(key) {
    const dict = this.t[this.lang] || this.t.en;
    return dict[key] != null ? dict[key] : (this.t.en[key] || key);
  },

  setLang(lang) {
    this.lang = lang === 'fa' ? 'fa' : 'en';
    localStorage.setItem('fl-lang', this.lang);
    document.documentElement.lang = this.lang;
    document.documentElement.dir = this.lang === 'fa' ? 'rtl' : 'ltr';
    this.apply();
  },

  apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.get(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.get(el.getAttribute('data-i18n-placeholder'));
    });
    // Update select options that have data-i18n-option
    document.querySelectorAll('option[data-i18n]').forEach(opt => {
      opt.textContent = this.get(opt.getAttribute('data-i18n'));
    });
  }
